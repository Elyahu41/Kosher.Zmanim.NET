using System.Diagnostics.CodeAnalysis;
using System.Globalization;
using System.Reflection;
using System.Text;

namespace Kosher.Zmanim.Util;

/// <summary>
/// A class used to format both <see cref="DateTimeOffset"/> times generated by the Zmanim package as well as <see cref="TimeSpan"/>
/// used for temporal hours / <em>sha'os zmaniyos</em>. For example the <see cref="AstronomicalCalendar.GetTemporalHour()"/> returns
/// the length of the hour as a <see cref="TimeSpan"/>.
/// </summary>
public class ZmanimFormatter
{
    /// <summary>
    /// Format using hours, minutes, seconds and milliseconds using the xsd:time format. This format will return
    /// <c>00.00.00.0</c> when formatting 0.
    /// </summary>
    public const int SexagesimalXsdFormat = 0;

    /// <summary>
    /// Format using hours and minutes.
    /// </summary>
    public const int SexagesimalFormat = 1;

    /// <summary>
    /// Format using hours, minutes and seconds.
    /// </summary>
    public const int SexagesimalSecondsFormat = 2;

    /// <summary>
    /// Format using hours, minutes, seconds and milliseconds.
    /// </summary>
    public const int SexagesimalMillisFormat = 3;

    /// <summary>
    /// Format using the XSD Duration format. This is in the format of PT1H6M7.869S (P for period (duration), T for time,
    /// H, M and S indicate hours, minutes and seconds.
    /// </summary>
    public const int XsdDurationFormat = 4;

    /// <summary>The xsd:dateTime pattern (the equivalent of Java's <c>yyyy-MM-dd'T'HH:mm:ssXXX</c>).</summary>
    private const string XsdDateTimePattern = "yyyy-MM-dd'T'HH:mm:ssK";

    /// <summary>
    /// Setting to prepend a zero to single digit hours.
    /// </summary>
    private bool prependZeroHours;

    /// <summary>
    /// Should seconds be used in formatting time.
    /// </summary>
    private bool useSeconds;

    /// <summary>
    /// Should milliseconds be used in formatting time.
    /// </summary>
    private bool useMillis;

    /// <summary>
    /// The duration format constant in use. Set by the constructor; defaults to <see cref="SexagesimalSecondsFormat"/> when using
    /// the single-argument constructor.
    /// </summary>
    private int timeFormat;

    /// <summary>
    /// Default constructor that uses the format "<c>h:mm:ss</c>" for dates and "<c>0:00:00</c>" for <see cref="TimeSpan"/>s.
    /// </summary>
    /// <param name="timeZone">the <see cref="TimeZoneInfo"/> times are formatted in.</param>
    public ZmanimFormatter(TimeZoneInfo timeZone)
        : this(SexagesimalSecondsFormat, "h:mm:ss", timeZone)
    {
    }

    /// <summary>
    /// ZmanimFormatter constructor using various formatting options.
    /// </summary>
    /// <param name="timeFormat">The formatting style to use for <see cref="TimeSpan"/> used to represent <em>shaos zmaniyos</em>. The
    ///         formatting will be as follows.<list type="bullet">
    ///         <item><see cref="SexagesimalSecondsFormat"/> (the default) - Will format an hour and a half as "<c>1:30:00</c>", and half
    ///         an hour as "<c>0:30:00</c>".</item>
    ///         <item><see cref="SexagesimalXsdFormat"/> - Will format an hour and a half as "<c>01:30:00.000</c>", and half an
    ///         hour as "<c>00:30:00.000</c>".</item>
    ///         <item><see cref="SexagesimalMillisFormat"/> - Will format an hour and a half as "<c>1:30:00.000</c>", and half an hour as
    ///         "<c>0:30:00.000</c>".</item>
    ///         <item><see cref="SexagesimalFormat"/> will format an hour and a half as "<c>1:30</c>", and half an hour as
    ///         "<c>0:30</c>".</item>
    ///         <item><see cref="XsdDurationFormat"/> will format the time as : "<c>PT1H30M</c>", and half an hour as "<c>PT30M</c>".</item>
    ///         </list></param>
    /// <param name="dateTimeFormat">a .NET <see href="https://learn.microsoft.com/dotnet/standard/base-types/custom-date-and-time-format-strings">custom
    ///         date and time format string</see> used by <see cref="FormatInstant"/>, such as <c>"h:mm:ss"</c>.</param>
    /// <param name="timeZone">the <see cref="TimeZoneInfo"/> times are formatted in.</param>
    public ZmanimFormatter(int timeFormat, string dateTimeFormat, TimeZoneInfo timeZone)
    {
        TimeZone = timeZone;
        SetTimeFormat(timeFormat);
        DateTimeFormat = dateTimeFormat;
    }

    /// <summary>
    /// The <see cref="TimeZoneInfo"/> used for formatting times.
    /// </summary>
    public TimeZoneInfo TimeZone { get; set; }

    /// <summary>
    /// The .NET custom date and time format string used by <see cref="FormatInstant"/> (the equivalent of the
    /// <c>DateTimeFormatter</c> in KosherJava).
    /// </summary>
    public string DateTimeFormat { get; set; }

    /// <summary>
    /// The culture used when formatting times with <see cref="DateTimeFormat"/>. Defaults to the invariant culture.
    /// </summary>
    public IFormatProvider FormatProvider { get; set; } = CultureInfo.InvariantCulture;

    /// <summary>
    /// Sets the time format to use for formatting <see cref="TimeSpan"/>s.
    /// </summary>
    /// <param name="format">the format constant to use. See <see cref="ZmanimFormatter(int, string, TimeZoneInfo)"/> for documentation
    ///         on the formats.</param>
    /// <exception cref="ArgumentException">if the format is not one of the format constants.</exception>
    public void SetTimeFormat(int format)
    {
        switch (format)
        {
            case SexagesimalXsdFormat:
                SetSettings(true, true, true);
                break;
            case SexagesimalFormat:
                SetSettings(false, false, false);
                break;
            case SexagesimalSecondsFormat:
                SetSettings(false, true, false);
                break;
            case SexagesimalMillisFormat:
                SetSettings(false, true, true);
                break;
            case XsdDurationFormat:
                break; // the settings are N/A for this
            default:
                throw new ArgumentException("An invalid time format of " + format +
                    " was set. Please see the documentation for the list of valid formats.", nameof(format));
        }
        timeFormat = format;
    }

    /// <summary>
    /// Sets various format settings.
    /// </summary>
    /// <param name="prependZeroHours">if to prepend a zero for single digit hours (so that 1 o'clock is displayed as 01).</param>
    /// <param name="useSeconds">should seconds be used in the time format.</param>
    /// <param name="useMillis">should milliseconds be used in formatting time.</param>
    private void SetSettings(bool prependZeroHours, bool useSeconds, bool useMillis)
    {
        this.prependZeroHours = prependZeroHours;
        this.useSeconds = useSeconds;
        this.useMillis = useMillis;
    }

    /// <summary>
    /// A method that formats a <see cref="TimeSpan"/> into a <see cref="string"/> format of "<c>00:00</c>", "<c>00:00:00</c>" or
    /// "<c>00:00:00.000</c>" depending on the settings of the formatter. See the documentation on
    /// <see cref="ZmanimFormatter(int, string, TimeZoneInfo)"/> for details.
    /// </summary>
    /// <param name="duration">The <see cref="TimeSpan"/> to format. <c>null</c> is formatted as zero.</param>
    /// <returns>The formatted <see cref="string"/>.</returns>
    public string Format(TimeSpan? duration)
    {
        TimeSpan value = duration ?? TimeSpan.Zero;
        if (timeFormat == XsdDurationFormat)
        {
            return FormatXSDDurationTime(value);
        }
        var sb = new StringBuilder();
        if (value < TimeSpan.Zero)
        {
            sb.Append('-');
        }
        TimeSpan abs = value.Duration();
        long hours = (long)abs.TotalHours;
        long minutes = (long)abs.TotalMinutes % 60;
        long seconds = (long)abs.TotalSeconds % 60;
        long milliseconds = JavaTime.ToMillis(abs) % 1000;
        sb.Append(hours.ToString(prependZeroHours ? "00" : "0", CultureInfo.InvariantCulture));
        sb.Append(':');
        sb.Append(minutes.ToString("00", CultureInfo.InvariantCulture));
        if (useSeconds)
        {
            sb.Append(':');
            sb.Append(seconds.ToString("00", CultureInfo.InvariantCulture));
        }
        if (useMillis)
        {
            sb.Append('.');
            sb.Append(milliseconds.ToString("000", CultureInfo.InvariantCulture));
        }
        return sb.ToString();
    }

    /// <summary>
    /// Formats a <see cref="DateTimeOffset"/> using this class's <see cref="DateTimeFormat"/>.
    /// </summary>
    /// <param name="instant">the <see cref="DateTimeOffset"/> to format.</param>
    /// <param name="timeZone">the <see cref="TimeZoneInfo"/> used to help format based on the <see cref="DateTimeOffset"/>'s DST and
    ///         other settings.</param>
    /// <returns>the formatted string</returns>
    /// <seealso cref="FormatXSDateTime"/>
    public string FormatInstant(DateTimeOffset instant, TimeZoneInfo timeZone)
    {
        return JavaTime.InZone(instant, timeZone).ToString(DateTimeFormat, FormatProvider);
    }

    /// <summary>
    /// Format the <see cref="DateTimeOffset"/> using the format "<c>yyyy-MM-dd'T'HH:mm:ssK</c>" (xsd:dateTime) in
    /// <see cref="TimeZone"/>.
    /// </summary>
    /// <param name="instant">the <see cref="DateTimeOffset"/> to format.</param>
    /// <returns>the <see cref="DateTimeOffset"/> formatted using the format "<c>yyyy-MM-dd'T'HH:mm:ssK</c>".</returns>
    public string FormatXSDateTime(DateTimeOffset instant)
    {
        return FormatXsd(instant, TimeZone);
    }

    /// <summary>
    /// This returns the xml representation of an xsd:duration object. This uses the ISO-8601 format that
    /// KosherJava's <c>Duration.toString()</c> uses (e.g., "<c>PT1H30M</c>").
    /// </summary>
    /// <param name="duration">the duration to format</param>
    /// <returns>the xsd:duration ISO-8601 formatted string</returns>
    public string FormatXSDDurationTime(TimeSpan? duration)
    {
        return duration == null ? string.Empty : JavaTime.DurationToString(duration);
    }

    /// <summary>
    /// Formats a time in xsd:dateTime format with a <c>Z</c> offset for UTC (matching Java's <c>XXX</c> pattern).
    /// </summary>
    private static string FormatXsd(DateTimeOffset instant, TimeZoneInfo zone)
    {
        DateTimeOffset local = JavaTime.InZone(instant, zone);
        string text = local.ToString("yyyy-MM-dd'T'HH:mm:ss", CultureInfo.InvariantCulture);
        return text + (local.Offset == TimeSpan.Zero ? "Z" : local.ToString("zzz", CultureInfo.InvariantCulture));
    }

    /// <summary>
    /// A method that returns an XML formatted <see cref="string"/> representing the serialized calendar. The format used is:
    /// <code>
    ///  &lt;AstronomicalTimes date="1969-02-08" type="Kosher.Zmanim.AstronomicalCalendar"
    ///         algorithm="US Naval Almanac Algorithm" location="Montreal, Quebec" latitude="45.497" longitude="-73.63"
    ///         elevation="85.0" timeZoneName="Eastern Standard Time" timeZoneID="America/New_York" timeZoneOffset="-5.0"&gt;
    ///     &lt;SeaLevelSunset&gt;1969-02-08T17:11:26-05:00&lt;/SeaLevelSunset&gt;
    ///     &lt;TemporalHour&gt;PT50M23.259S&lt;/TemporalHour&gt;
    ///     ...
    ///   &lt;/AstronomicalTimes&gt;
    /// </code>
    /// If a zman does not occur, the value "N/A" will be returned.
    /// <para>Note that the output uses the <a href="http://www.w3.org/TR/xmlschema11-2/#dateTime">xsd:dateTime</a> format for
    /// times such as sunrise, and <a href="http://www.w3.org/TR/xmlschema11-2/#duration">xsd:duration</a> format for
    /// times that are a duration such as the length of a
    /// <see cref="AstronomicalCalendar.GetTemporalHour()">temporal hour</see>. The output of this method is
    /// returned by <see cref="AstronomicalCalendar.ToString"/>.</para>
    /// <para>Every public, parameterless <c>Get*</c> method of the calendar that returns a <see cref="DateTimeOffset"/> or
    /// <see cref="TimeSpan"/> is included, discovered with reflection.</para>
    /// </summary>
    /// <param name="astronomicalCalendar">the AstronomicalCalendar Object</param>
    /// <returns>The XML <see cref="string"/> formatted as described above.</returns>
    /// <remarks>
    /// <b>To do:</b> Add proper schema, and support for nulls. XSD duration (for solar hours), should probably return nil and not P.
    /// </remarks>
    [RequiresUnreferencedCode("Discovers zmanim methods with reflection.")]
    public static string ToXml(AstronomicalCalendar astronomicalCalendar)
    {
        Metadata meta = GetMetadata(astronomicalCalendar);
        var sb = new StringBuilder("<");
        if (meta.RootName != null)
        {
            sb.Append(meta.RootName);
        }
        sb.Append(" date=\"").Append(meta.Date).Append('"');
        sb.Append(" type=\"").Append(meta.Type).Append('"');
        sb.Append(" algorithm=\"").Append(meta.Algorithm).Append('"');
        sb.Append(" location=\"").Append(meta.Location).Append('"');
        sb.Append(" latitude=\"").Append(meta.Latitude).Append('"');
        sb.Append(" longitude=\"").Append(meta.Longitude).Append('"');
        sb.Append(" elevation=\"").Append(meta.Elevation).Append('"');
        sb.Append(" timeZoneName=\"").Append(meta.TimeZoneName).Append('"');
        sb.Append(" timeZoneID=\"").Append(meta.TimeZoneId).Append('"');
        sb.Append(" timeZoneOffset=\"").Append(meta.TimeZoneOffset).Append('"');
        sb.Append(">\n");

        var formatter = new ZmanimFormatter(XsdDurationFormat, "yyyy-MM-dd'T'HH:mm:ss", astronomicalCalendar.GeoLocation.TimeZone);
        CollectValues(astronomicalCalendar, out List<Zman> dateList, out List<Zman> durationList, out List<string> naList);
        foreach (Zman zman in dateList)
        {
            sb.Append("\t<").Append(zman.Label).Append('>');
            sb.Append(FormatXsd(zman.Time!.Value, astronomicalCalendar.GeoLocation.TimeZone));
            sb.Append("</").Append(zman.Label).Append(">\n");
        }
        foreach (Zman zman in durationList)
        {
            sb.Append("\t<").Append(zman.Label).Append('>');
            sb.Append(formatter.Format(zman.Duration)).Append("</").Append(zman.Label).Append(">\n");
        }
        foreach (string tagName in naList)
        {
            sb.Append("\t<").Append(tagName).Append(">N/A</").Append(tagName).Append(">\n");
        }
        if (meta.RootName != null)
        {
            sb.Append("</").Append(meta.RootName).Append('>');
        }
        return sb.ToString();
    }

    /// <summary>
    /// A method that returns a JSON formatted <see cref="string"/> representing the serialized calendar. The format used is:
    /// <code>
    /// {
    ///    "metadata":{
    ///      "date":"1969-02-08",
    ///      "type":"Kosher.Zmanim.AstronomicalCalendar",
    ///      "algorithm":"US Naval Almanac Algorithm",
    ///      "location":"Montreal, Quebec",
    ///      "latitude":"45.497",
    ///      "longitude":"-73.63",
    ///      "elevation:"85.0",
    ///      "timeZoneName":"Eastern Standard Time",
    ///      "timeZoneID":"America/New_York",
    ///      "timeZoneOffset":"-5.0"},
    ///    "AstronomicalTimes":{
    ///     "Sunrise":"2007-02-18T06:45:27-05:00",
    ///     "TemporalHour":"PT52M35.519S"
    ///     ...
    ///     }
    /// }
    /// </code>
    /// <para>Note that the output uses the <a href="http://www.w3.org/TR/xmlschema11-2/#dateTime">xsd:dateTime</a> format for
    /// times such as sunrise, and <a href="http://www.w3.org/TR/xmlschema11-2/#duration">xsd:duration</a> format for
    /// times that are a duration such as the length of a
    /// <see cref="AstronomicalCalendar.GetTemporalHour()">temporal hour</see>.</para>
    /// </summary>
    /// <param name="astronomicalCalendar">the AstronomicalCalendar Object</param>
    /// <returns>The JSON formatted <see cref="string"/> as described above.</returns>
    [RequiresUnreferencedCode("Discovers zmanim methods with reflection.")]
    public static string ToJson(AstronomicalCalendar astronomicalCalendar)
    {
        Metadata meta = GetMetadata(astronomicalCalendar);
        var sb = new StringBuilder("{\n\"metadata\":{\n");
        sb.Append("\t\"date\":\"").Append(meta.Date).Append("\",\n");
        sb.Append("\t\"type\":\"").Append(meta.Type).Append("\",\n");
        sb.Append("\t\"algorithm\":\"").Append(meta.Algorithm).Append("\",\n");
        sb.Append("\t\"location\":\"").Append(meta.Location).Append("\",\n");
        sb.Append("\t\"latitude\":\"").Append(meta.Latitude).Append("\",\n");
        sb.Append("\t\"longitude\":\"").Append(meta.Longitude).Append("\",\n");
        sb.Append("\t\"elevation\":\"").Append(meta.Elevation).Append("\",\n");
        sb.Append("\t\"timeZoneName\":\"").Append(meta.TimeZoneName).Append("\",\n");
        sb.Append("\t\"timeZoneID\":\"").Append(meta.TimeZoneId).Append("\",\n");
        sb.Append("\t\"timeZoneOffset\":\"").Append(meta.TimeZoneOffset).Append('"');
        sb.Append("},\n\"");
        if (meta.RootName != null)
        {
            sb.Append(meta.RootName);
        }
        sb.Append("\":{\n");

        var formatter = new ZmanimFormatter(XsdDurationFormat, "yyyy-MM-dd'T'HH:mm:ss", astronomicalCalendar.GeoLocation.TimeZone);
        CollectValues(astronomicalCalendar, out List<Zman> dateList, out List<Zman> durationList, out List<string> naList);
        foreach (Zman zman in dateList)
        {
            sb.Append("\t\"").Append(zman.Label).Append("\":\"");
            sb.Append(FormatXsd(zman.Time!.Value, astronomicalCalendar.GeoLocation.TimeZone));
            sb.Append("\",\n");
        }
        foreach (Zman zman in durationList)
        {
            sb.Append("\t\"").Append(zman.Label).Append("\":\"");
            sb.Append(formatter.Format(zman.Duration)).Append("\",\n");
        }
        foreach (string tagName in naList)
        {
            sb.Append("\t\"").Append(tagName).Append("\":\"N/A\",\n");
        }
        sb.Length -= 2; // remove the last comma and newline
        sb.Append("}\n}");
        return sb.ToString();
    }

    /// <summary>The header values shared by <see cref="ToXml"/> and <see cref="ToJson"/>.</summary>
    private sealed record Metadata(string? RootName, string Date, string Type, string Algorithm, string? Location, string Latitude,
        string Longitude, string Elevation, string TimeZoneName, string TimeZoneId, string TimeZoneOffset);

    /// <summary>Builds the header values for a calendar.</summary>
    private static Metadata GetMetadata(AstronomicalCalendar calendar)
    {
        GeoLocation geoLocation = calendar.GeoLocation;
        DateTimeOffset lastMidnight = JavaTime.AtZone(calendar.LocalDate, TimeOnly.MinValue, geoLocation.TimeZone);
        double offsetHours = lastMidnight.Offset.TotalSeconds / 3600.0;
        string timeZoneName = geoLocation.TimeZone.IsDaylightSavingTime(lastMidnight)
            ? geoLocation.TimeZone.DaylightName : geoLocation.TimeZone.StandardName;
        Type type = calendar.GetType();
        string? root = type == typeof(AstronomicalCalendar) ? "AstronomicalTimes"
            : type == typeof(ComprehensiveZmanimCalendar) ? "Zmanim"
            : type == typeof(ZmanimCalendar) ? "BasicZmanim"
            : null;
        return new Metadata(root, calendar.LocalDate.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture), type.FullName ?? type.Name,
            calendar.AstronomicalCalculator.CalculatorName, geoLocation.LocationName, JavaMath.ToJavaString(geoLocation.Latitude),
            JavaMath.ToJavaString(geoLocation.Longitude), JavaMath.ToJavaString(geoLocation.Elevation), timeZoneName,
            geoLocation.TimeZone.Id, JavaMath.ToJavaString(offsetHours));
    }

    /// <summary>
    /// Invokes every included method (see <see cref="IncludeMethod"/>) and sorts the results into times, durations and
    /// <em>zmanim</em> that do not occur.
    /// </summary>
    [RequiresUnreferencedCode("Discovers zmanim methods with reflection.")]
    private static void CollectValues(AstronomicalCalendar calendar, out List<Zman> dateList, out List<Zman> durationList,
        out List<string> naList)
    {
        dateList = new List<Zman>();
        durationList = new List<Zman>();
        naList = new List<string>();
        foreach (MethodInfo method in calendar.GetType().GetMethods(BindingFlags.Public | BindingFlags.Instance))
        {
            if (!IncludeMethod(method))
            {
                continue;
            }
            string tagName = method.Name.Substring(3);
            object? value;
            try
            {
                value = method.Invoke(calendar, null);
            }
            catch (TargetInvocationException)
            {
                continue;
            }
            switch (value)
            {
                case null:
                    naList.Add(tagName);
                    break;
                case DateTimeOffset time:
                    dateList.Add(new Zman(time, tagName));
                    break;
                case TimeSpan duration:
                    durationList.Add(new Zman(duration, tagName));
                    break;
            }
        }
        dateList.Sort(Zman.DateOrder);
        durationList.Sort(Zman.DurationOrder);
    }

    /// <summary>
    /// Determines if a method should be output by the <see cref="ToXml"/> and <see cref="ToJson"/> methods: public, parameterless
    /// <c>Get*</c> methods that return a <see cref="DateTimeOffset"/> or <see cref="TimeSpan"/> (nullable or not).
    /// </summary>
    /// <param name="method">the method in question</param>
    /// <returns>if the method should be included in serialization</returns>
    private static bool IncludeMethod(MethodInfo method)
    {
        if (method.GetParameters().Length > 0 || method.IsSpecialName || !method.Name.StartsWith("Get", StringComparison.Ordinal))
        {
            return false;
        }
        Type returnType = Nullable.GetUnderlyingType(method.ReturnType) ?? method.ReturnType;
        return returnType == typeof(DateTimeOffset) || returnType == typeof(TimeSpan);
    }
}
